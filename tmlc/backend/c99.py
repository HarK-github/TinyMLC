"""C99 code generator for TinyML model inference."""

from __future__ import annotations

import pathlib
from typing import Final

import numpy as np

from tmlc.backend.templates import (
    dense_loop_c,
    dense_loop_int8_c,
    dense_relu_loop_c,
    dense_relu_loop_int8_c,
    relu_loop_c,
    softmax_loop_c,
)
from tmlc.errors import TmlcError
from tmlc.ir.builder import IRProgram
from tmlc.ir.ops import OpKind
from tmlc.optimizer.buffers import MemoryReport


def format_c_float(val: float) -> str:
    """Format float using exact %.9g with C float literal suffix ('f')."""
    s = f"{val:.9g}"
    if "." in s or "e" in s or "E" in s:
        return f"{s}f"
    return f"{s}.0f"


def format_array_c(name: str, arr: np.ndarray, items_per_line: int = 8) -> str:
    """Format flattened numpy float array as static const C definition."""
    flat = arr.flatten()
    total_elements = len(flat)
    lines: list[str] = [f"static const float {name}[{total_elements}] = {{"]

    for i in range(0, total_elements, items_per_line):
        chunk = flat[i : i + items_per_line]
        chunk_str = ", ".join(format_c_float(float(x)) for x in chunk)
        if i + items_per_line < total_elements:
            lines.append(f"    {chunk_str},")
        else:
            lines.append(f"    {chunk_str}")

    lines.append("};")
    return "\n".join(lines)


def format_array_int8_c(name: str, arr: np.ndarray, items_per_line: int = 16) -> str:
    """Format flattened numpy int8 array as static const C definition."""
    flat = arr.flatten()
    total_elements = len(flat)
    lines: list[str] = [f"static const int8_t {name}[{total_elements}] = {{"]

    for i in range(0, total_elements, items_per_line):
        chunk = flat[i : i + items_per_line]
        chunk_str = ", ".join(str(int(x)) for x in chunk)
        if i + items_per_line < total_elements:
            lines.append(f"    {chunk_str},")
        else:
            lines.append(f"    {chunk_str}")

    lines.append("};")
    return "\n".join(lines)


class C99Backend:
    """Emits standalone ANSI C99 implementation (model.c) and header (model.h)."""

    def generate_header(self, program: IRProgram) -> str:
        """Generate model.h with dimension macros, declarations, and include guards."""
        guard_macro: Final[str] = f"TMLC_GENERATED_{program.name.upper()}_MODEL_H"
        is_quantized = any(op.quantized_weights is not None for op in program.ops)
        if is_quantized:
            extra_includes = "#include <stdint.h>\n\n"
            extra_macros = "#define MODEL_INPUT_SIZE MODEL_INPUT_DIM\n#define MODEL_OUTPUT_SIZE MODEL_OUTPUT_DIM\n"
        else:
            extra_includes = ""
            extra_macros = ""
        return f"""/*
 * Auto-generated header for TinyML model: {program.name}
 * Generated by TMLC (TinyML Model-to-C Compiler)
 * Zero dynamic allocation; MCU-ready standalone ANSI C99.
 */

#ifndef {guard_macro}
#define {guard_macro}

{extra_includes}#ifdef __cplusplus
extern "C" {{
#endif

#define MODEL_NAME "{program.name}"
#define MODEL_INPUT_DIM {program.input_dim}
#define MODEL_OUTPUT_DIM {program.output_dim}
{extra_macros}
/**
 * Run forward inference on a single input vector.
 *
 * @param input  Pointer to input array of size MODEL_INPUT_DIM ({program.input_dim} floats).
 * @param output Pointer to output array of size MODEL_OUTPUT_DIM ({program.output_dim} floats).
 */
void model_predict(const float input[{program.input_dim}], float output[{program.output_dim}]);

#ifdef __cplusplus
}}
#endif

#endif /* {guard_macro} */
"""

    def generate_source(self, program: IRProgram, report: MemoryReport) -> str:
        """Generate model.c embedding weights and generating forward inference loop."""
        is_quantized = any(op.quantized_weights is not None for op in program.ops)
        if is_quantized:
            header_include = '#include "model.h"\n#include <math.h>\n#include <stdint.h>\n'
        else:
            header_include = '#include "model.h"\n#include <math.h>\n'

        # 1. Weight definitions
        weight_defs: list[str] = []
        layer_counter = 0

        # We will collect weight variable names for each op: (w_var, b_var, scale_var | None)
        op_weight_names: dict[int, tuple[str, str, str | None]] = {}

        for op_idx, op in enumerate(program.ops):
            if op.kind in (OpKind.DENSE, OpKind.DENSE_RELU):
                if op.bias is None or (op.weights is None and op.quantized_weights is None):
                    raise TmlcError(
                        "E501",
                        f"Dense operation {op.kind.value} missing weights or bias",
                    )

                layer_counter += 1
                w_var = f"layer{layer_counter}_weights"
                b_var = f"layer{layer_counter}_bias"
                b_c = format_array_c(b_var, op.bias)

                if op.quantized_weights is not None:
                    if op.scale is None:
                        raise TmlcError("E501", f"Layer {layer_counter} missing int8 scale")
                    scale_var = f"layer{layer_counter}_scale"
                    scale_c = f"static const float {scale_var} = {format_c_float(float(op.scale))};"
                    w_c = format_array_int8_c(w_var, op.quantized_weights)

                    weight_defs.append(
                        f"/* Layer {layer_counter}: {op.kind.value}({op.in_dim} -> {op.out_dim}) [int8 quantized] */"
                    )
                    weight_defs.append(scale_c)
                    weight_defs.append(w_c)
                    weight_defs.append(b_c)
                    weight_defs.append("")

                    op_weight_names[op_idx] = (w_var, b_var, scale_var)
                else:
                    assert op.weights is not None
                    w_c = format_array_c(w_var, op.weights)

                    weight_defs.append(
                        f"/* Layer {layer_counter}: {op.kind.value}({op.in_dim} -> {op.out_dim}) */"
                    )
                    weight_defs.append(w_c)
                    weight_defs.append(b_c)
                    weight_defs.append("")

                    op_weight_names[op_idx] = (w_var, b_var, None)

        # 2. Static buffer definitions
        buf_defs: list[str] = [
            "/* Static working buffers (zero dynamic allocation) */",
            f"static float buf_a[{max(report.buffer_a_floats, 1)}];",
            f"static float buf_b[{max(report.buffer_b_floats, 1)}];",
            "",
        ]

        # 3. Model predict function body
        body_lines: list[str] = [
            f"void model_predict(const float input[{program.input_dim}], float output[{program.output_dim}]) {{",
        ]

        # Process each operation
        for op_idx, op in enumerate(program.ops):
            src_buf = op.input_buf
            dst_buf = op.output_buf

            if op.kind == OpKind.INPUT:
                # Direct pointer pass
                continue

            elif op.kind == OpKind.DENSE:
                w_name, b_name, scale_name = op_weight_names[op_idx]
                if scale_name is not None:
                    body_lines.append(
                        dense_loop_int8_c(
                            op.in_dim, op.out_dim, w_name, b_name, scale_name, src_buf, dst_buf
                        )
                    )
                else:
                    body_lines.append(
                        dense_loop_c(
                            op.in_dim, op.out_dim, w_name, b_name, src_buf, dst_buf
                        )
                    )

            elif op.kind == OpKind.DENSE_RELU:
                w_name, b_name, scale_name = op_weight_names[op_idx]
                if scale_name is not None:
                    body_lines.append(
                        dense_relu_loop_int8_c(
                            op.in_dim, op.out_dim, w_name, b_name, scale_name, src_buf, dst_buf
                        )
                    )
                else:
                    body_lines.append(
                        dense_relu_loop_c(
                            op.in_dim, op.out_dim, w_name, b_name, src_buf, dst_buf
                        )
                    )

            elif op.kind == OpKind.RELU:
                body_lines.append(relu_loop_c(op.in_dim, src_buf))

            elif op.kind == OpKind.SOFTMAX:
                body_lines.append(softmax_loop_c(op.in_dim, src_buf, dst_buf))

            elif op.kind == OpKind.OUTPUT:
                # If output is not already in the destination buffer, copy it
                if src_buf != "output":
                    body_lines.append(
                        f"    /* Final output copy: {src_buf} to output */"
                    )
                    body_lines.append(f"    for (int i = 0; i < {op.out_dim}; i++) {{")
                    body_lines.append(f"        output[i] = {src_buf}[i];")
                    body_lines.append("    }")

            else:
                raise TmlcError(
                    "E501", f"Unsupported backend operation: {op.kind.value}"
                )

        body_lines.append("}")

        # Combine all sections
        c_code = (
            "/*\n"
            f" * Auto-generated C99 implementation for TinyML model: {program.name}\n"
            " * Generated by TMLC (TinyML Model-to-C Compiler)\n"
            " * Microcontroller compatible: static RAM, static const weights, zero dynamic allocation, no file I/O.\n"
            " */\n\n"
            + header_include
            + "\n"
            + "\n".join(weight_defs)
            + "\n".join(buf_defs)
            + "\n".join(body_lines)
            + "\n"
        )
        return c_code

    def generate(
        self,
        program: IRProgram,
        report: MemoryReport,
        out_dir: str | pathlib.Path = "generated",
    ) -> tuple[pathlib.Path, pathlib.Path]:
        """Emit both model.c and model.h to the specified directory."""
        dest = pathlib.Path(out_dir)
        dest.mkdir(parents=True, exist_ok=True)

        h_code = self.generate_header(program)
        c_code = self.generate_source(program, report)

        h_path = dest / "model.h"
        c_path = dest / "model.c"

        h_path.write_text(h_code, encoding="utf-8")
        c_path.write_text(c_code, encoding="utf-8")

        return c_path, h_path
